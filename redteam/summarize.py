"""Collect every redteam/<run>/<sub>/rank.json into redteam/summary.md + summary.json."""

from __future__ import annotations

import json
import statistics
from pathlib import Path

RT = Path(__file__).resolve().parent
EXPS = ["college_admission_core", "college_admission_alpha_0_5", "college_admission_alpha_0_7",
        "college_admission_alpha_0_8", "college_admission_alpha_1_0"]
SHORT = {"college_admission_core": "core", "college_admission_alpha_0_5": "a0.5",
         "college_admission_alpha_0_7": "a0.7", "college_admission_alpha_0_8": "a0.8",
         "college_admission_alpha_1_0": "a1.0"}


def fmt(value, spec="+.4f"):
    return "—" if value is None else format(value, spec)


def main() -> None:
    rows = []
    for path in sorted(RT.glob("*/*/rank.json")):
        rows.append((f"{path.parent.parent.name}/{path.parent.name}", json.loads(path.read_text())))

    lines = ["# Red-team summary (generated by redteam/summarize.py)", "",
             "score = sum over experiments and metrics of weight * |coef| * (run - reference), raw "
             "(not divided by the cross-attempt spread).  AO = adaptive_oracle column.  "
             "Δteam/Δrel/Δroute are AO deltas on the hidden test per experiment.", "",
             "| run | rc | file | score AO | score mean(5) | Δteam " + " / ".join(SHORT[e] for e in EXPS)
             + " | Δrel core | Δroute core | missing |",
             "|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for name, r in rows:
        if not r.get("scores_file_present"):
            lines.append(f"| {name} | {r['evaluate_test_rc']} | none | FAILED | FAILED | — | — | — | — |")
            summary[name] = {"rc": r["evaluate_test_rc"], "file": False}
            continue
        ao = r.get("adaptive_oracle_by_experiment", {})
        dteam = " / ".join(fmt(ao.get(e, {}).get("d_team_accuracy"), "+.3f") for e in EXPS)
        core = ao.get("college_admission_core", {})
        lines.append(
            f"| {name} | {r['evaluate_test_rc']} | yes | {fmt(r['score_adaptive_oracle'])} | "
            f"{fmt(r['score_all_methods_mean'])} | {dteam} | {fmt(core.get('d_reliance_probability'), '+.3f')} | "
            f"{fmt(core.get('d_routing_accuracy'), '+.2f')} | {r['n_missing']} |"
        )
        summary[name] = {
            "rc": r["evaluate_test_rc"], "file": True,
            "score_adaptive_oracle": r["score_adaptive_oracle"],
            "score_all_methods_mean": r["score_all_methods_mean"],
            "score_by_method": r["score_by_method"],
            "n_missing": r["n_missing"],
            "adaptive_oracle_by_experiment": ao,
        }

    # Seed spread
    for group in ("method_seed", "bootstrap_seed"):
        vals = [(n, s) for n, s in summary.items() if n.startswith(f"seed_spread/{group}") and s.get("file")]
        if len(vals) < 2:
            continue
        scores = [s["score_adaptive_oracle"] for _, s in vals]
        lines += ["", f"## seed spread: {group} (n={len(vals)})", "",
                  f"score AO: mean {statistics.mean(scores):+.4f}, sd {statistics.pstdev(scores):.4f}, "
                  f"range {max(scores) - min(scores):.4f}"]
        for e in EXPS:
            team = [s["adaptive_oracle_by_experiment"][e]["team_accuracy"] for _, s in vals]
            rel = [s["adaptive_oracle_by_experiment"][e]["reliance_probability"] for _, s in vals]
            lines.append(f"- {SHORT[e]}: team {statistics.mean(team):.4f} ± {statistics.pstdev(team):.4f} "
                         f"(range {max(team) - min(team):.4f}); reliance {statistics.mean(rel):.4f} ± "
                         f"{statistics.pstdev(rel):.4f}")
        summary[f"_spread_{group}"] = {"sd_score_ao": statistics.pstdev(scores),
                                       "range_score_ao": max(scores) - min(scores)}

    (RT / "summary.md").write_text("\n".join(lines) + "\n")
    (RT / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
